from playwright.sync_api import sync_playwright
from pathlib import Path
import json
url='http://127.0.0.1:8777/index.html'
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':960})
 errs=[]
 page.on('pageerror',lambda e: errs.append(str(e)))
 page.goto('about:blank')
 page.evaluate("""() => {const mk=()=>{const d={};return {getItem(k){return d[k]??null},setItem(k,v){d[k]=String(v)},removeItem(k){delete d[k]},clear(){for(let k in d)delete d[k]}}};Object.defineProperty(window,'localStorage',{configurable:true,value:mk()});Object.defineProperty(window,'sessionStorage',{configurable:true,value:mk()})}""")
 page.set_content(Path('/mnt/data/AI_Risk_Lab_ClearUX/index.html').read_text(),wait_until='domcontentloaded')
 page.screenshot(path='/mnt/data/AI_Risk_Lab_ClearUX/home.png',full_page=True)
 print('home title',page.locator('#pageCrumb').inner_text())
 print('home cards',page.locator('.quick-action').count())
 page.locator("#navGroupMonitor summary").click();page.locator('.sidebar [data-target="monitor"]').click()
 page.screenshot(path='/mnt/data/AI_Risk_Lab_ClearUX/monitor.png',full_page=True)
 page.locator("#navGroupAssess summary").click();page.locator('.sidebar [data-target="checklist"]').click()
 print('checklist items',page.locator('#signalList details.signal').count())
 page.locator('#signalList details.signal').first.locator('summary').click()
 page.screenshot(path='/mnt/data/AI_Risk_Lab_ClearUX/checklist.png',full_page=False)
 page.locator('#signalList details.signal').first.locator('select[data-signal-new]').select_option('watch')
 print('summary',page.locator('#signalSummary').inner_text())
 page.locator('.sidebar [data-target="stockreviews"]').click()
 page.locator('#newTicker').fill('NVDA');page.locator('#addTicker').click()
 print('stock review',page.locator('#stockReviewBody h2').first.inner_text())
 page.locator('#companyChecks details.signal').first.locator('summary').click()
 page.locator('#companyChecks details.signal').first.locator('select[data-stock-kind="status"]').select_option('serious')
 page.screenshot(path='/mnt/data/AI_Risk_Lab_ClearUX/stock.png',full_page=False)
 print('saved StockReviews',page.evaluate('JSON.parse(localStorage.getItem("ai-risk-lab-v3")).fields.stockReviews.NVDA.review.F1'))
 # A new browser tab with seeded local storage simulates reopening after a reload.
 saved_state=page.evaluate('localStorage.getItem("ai-risk-lab-v3")')
 page2=browser.new_page(viewport={'width':1440,'height':960})
 page2.on('pageerror',lambda e:errs.append('reload: '+str(e)))
 page2.goto('about:blank')
 page2.evaluate("""stored => {const mk=()=>{const d={};return {getItem(k){return d[k]??null},setItem(k,v){d[k]=String(v)},removeItem(k){delete d[k]},clear(){for(let k in d)delete d[k]}}};let ls=mk(),ss=mk();ls.setItem('ai-risk-lab-v3',stored);Object.defineProperty(window,'localStorage',{configurable:true,value:ls});Object.defineProperty(window,'sessionStorage',{configurable:true,value:ss})}""",saved_state)
 page2.set_content(Path('/mnt/data/AI_Risk_Lab_ClearUX/index.html').read_text(),wait_until='domcontentloaded')
 page2.locator('#navGroupAssess summary').click();page2.locator('.sidebar [data-target="stockreviews"]').click()
 print('after reload stock',page2.locator('.stock-tag').count(), page2.locator('#companyChecks details.signal').first.locator('select').input_value())
 page2.close()
 page.locator("#navGroupTools summary").click();page.locator('.sidebar [data-target="portfolio"]').click()
 print('stress example',page.locator('#insight_portfolio').inner_text())
 page.screenshot(path='/mnt/data/AI_Risk_Lab_ClearUX/portfolio.png',full_page=False)
 print('errors',errs)
 browser.close()
